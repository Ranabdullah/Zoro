import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = new URL("../", import.meta.url);
export async function setupSql() {
  const migrations = [
    "schema",
    "access-hardening",
    "session-security",
    "public-registration",
    "delete-account",
    "backend-links",
    "phone-auth",
    "device-approval",
    "recovery-codes",
  ];
  const files = await Promise.all(
    migrations.map(async (name) => {
      const contents = await readFile(
        new URL(`supabase/${name}.sql`, root),
        "utf8",
      );
      return `-- SECTION: ${name}.sql\n${contents.replace(/\r\n/g, "\n").trim()}\n`;
    }),
  );
  return (
    "-- ZORO BACKEND SETUP — NEW, EMPTY SUPABASE PROJECTS ONLY\n-- Generated by npm run setup. Do not edit this combined file.\n-- Run the whole file once; public registration is enabled by the later sections.\n\n" +
    files.join("\n")
  );
}
if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const file = new URL("supabase/setup.sql", root),
    sql = await setupSql();
  if (process.argv.includes("--check")) {
    const existing = (await readFile(file, "utf8")).replace(/\r\n/g, "\n");
    if (existing !== sql)
      throw Error("Combined setup is stale. Run npm run setup.");
    console.log("Combined SQL matches all migrations.");
  } else {
    await writeFile(file, sql);
    console.log("Wrote supabase/setup.sql for a new project.");
  }
}
